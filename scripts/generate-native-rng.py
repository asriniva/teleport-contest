"""Bind the unchanged recorder RNG policy to its per-game JS state."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/rnd.js').read_text()
context="import { C } from '../c-runtime/context.js';"
isaac="import { isaac64_init, isaac64_next_uint64 } from '../isaac64.js';"
assert source.count(context)==1 and source.count(isaac)==1
names=re.findall(r'^export function (\w+)',source,re.M)
source=source.replace(context,'').replace(isaac,'')
source=re.sub(r'^export ','',source,flags=re.M)
(root/'js/nethack/native/rng.js').write_text('// Generated by scripts/generate-native-rng.py; algorithm, local calls and RNG order retained.\n'+isaac.replace("'../isaac64.js'","'../../isaac64.js'")+'\nexport function createNativeRng(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n')
