// Keep source policy and ordering; bind its dependencies once per native game.
import fs from 'node:fs';
import {parse} from 'acorn';
const groups={Geometry:['hacklib',['sgn','distmin','dist2','isqrt','online2']],Coordinates:['cmd',['isok']],Terrain:['dbridge',['is_waterwall','is_pool','is_lava','is_pool_or_lava','is_ice','is_moat','db_under_typ']],Engravings:['engrave',['engr_at','sengr_at']],Regions:['region',['inside_rect','inside_region','visible_region_at','any_visible_region']]};
let out='// Generated by scripts/generate-native-spatial.mjs; source policy/order retained.\n';
for(const [kind,[file,names]]of Object.entries(groups)){
 const source=fs.readFileSync(`js/ported/${file}.js`,'utf8'),ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),functions=new Map(ast.body.filter(n=>n.type==='ExportNamedDeclaration'&&n.declaration?.type==='FunctionDeclaration').map(n=>[n.declaration.id.name,n.declaration]));
 out+=`export function createNative${kind}Policy(C){\n`;
 for(const name of names){const n=functions.get(name);if(!n)throw Error('Missing original spatial policy '+name);out+=source.slice(n.start,n.end)+'\n';}
 out+='return {'+names.join(',')+'};\n}\n';
}
fs.writeFileSync('js/nethack/native/spatial-policy.js',out);
