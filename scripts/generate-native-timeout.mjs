// Bind the complete TIMEOUT policy graph and replace its C pointer walk with
// indexed native property iteration. Statement and RNG order remain unchanged.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {parse} from 'acorn';
const source=fs.readFileSync('js/ported/timeout.js','utf8'),ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),edits=[],names=[];
function walk(node){
 if(!node||typeof node!=='object')return;
 if(Array.isArray(node)){node.forEach(walk);return;}
 if(node.type==='ForStatement'&&source.slice(node.start,node.body.start).includes('upp.index')){
  assert.equal(source.slice(node.start,node.body.start).trim(),'for (upp = C.u.uprops[0]; upp.index < C.PROP_COUNT; upp = C.u.uprops[upp.index + 1])');
  edits.push([node.start,node.body.start,'for (let propertyIndex = 0; propertyIndex < C.PROP_COUNT; propertyIndex++) {\n        upp = C.u.uprops[propertyIndex];\n        '],[node.body.end,node.body.end,'\n    }']);
 }
 if(node.type==='MemberExpression'&&node.object.name==='upp'&&node.property.name==='index'){
  // The loop header is replaced as a unit above.
  if(!edits.some(([a,b])=>a<=node.start&&b>=node.end))edits.push([node.start,node.end,'propertyIndex']);
 }
 if(node.type==='CallExpression'&&node.callee.type==='MemberExpression'&&node.callee.object.name==='C'&&node.callee.property.name==='callLocal'){
  assert.equal(node.arguments[0].type,'Identifier');
  const first=node.arguments[0];edits.push([node.start,first.end,first.name]);
  // Replace the comma separating the function value from its arguments.
  if(node.arguments.length>1)edits.push([first.end,node.arguments[1].start,'(']);
  else edits.push([first.end,node.end,'()']);
 }
 for(const value of Object.values(node))walk(value);
}
for(const node of ast.body){
 if(node.type==='ImportDeclaration'){assert.equal(node.source.value,'../c-runtime/context.js');edits.push([node.start,node.end,'']);}
 if(node.type==='ExportNamedDeclaration'){const d=node.declaration;edits.push([node.start,d.start,'']);if(d.id)names.push(d.id.name);else names.push(...d.declarations.map(row=>row.id.name));}
}
walk(ast);
let body=source;for(const [a,b,value]of edits.sort((a,b)=>b[0]-a[0]))body=body.slice(0,a)+value+body.slice(b);
assert.ok(!body.includes('C.callLocal('));assert.ok(!body.includes('upp.index'));
const output='// Generated by scripts/generate-native-timeout.mjs; policy and RNG order retained.\nexport function createNativeTimeout(C) {\n'+body+'\nreturn {'+names.join(',')+'};\n}\n';
parse(output,{ecmaVersion:'latest',sourceType:'module'});fs.writeFileSync('js/nethack/native/timeout.js',output);
