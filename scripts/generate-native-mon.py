"""Generate per-game lifecycle policies without the global C execution scope."""
from pathlib import Path
import re
import sys
import os
import subprocess
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/mon.js').read_text()
names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
assert source.count("import {C} from '../c-runtime/context.js';")==1
source=source.replace("import {C} from '../c-runtime/context.js';",'')
source=re.sub(r'^export ','',source,flags=re.M)
source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
assert 'C.callLocal(' not in source
# The iteration diagnostic has no byte consumer on the ordinary path.
start=source.index('function dmonsfree(')
end=source.index('function replmon(',start)
body=source[start:end]
assert body.count('const buf=C.stackAlloc(C.QBUFSZ);')==1
assert body.count('C.storeChar(C.ptrOffset(buf, 0), 0);')==1
body=body.replace('const buf=C.stackAlloc(C.QBUFSZ);','const buf=C.nativeByteBuffer(C.QBUFSZ);').replace('C.storeChar(C.ptrOffset(buf, 0), 0);','C.storeCharAt(buf, 0, 0);')
source=source[:start]+body+source[end:]
# The safe iterator owns a native JS snapshot; growth/release policy stays original.
start=source.index('function alloc_itermonarr(')
end=source.index('function iter_mons_safe(',start)
body=source[start:end]
assert body.count('C.free( C.itermonarr)')==1
body=body.replace('C.free( C.itermonarr)','C.freeMonsterSnapshot(C.itermonarr)')
old='C.alloc(\n                                        C.ulong((C.ulong(C.itermonsiz) * C.ulong(C.pointerSize))))'
assert body.count(old)==1
body=body.replace(old,'C.nativeMonsterSnapshot(C.itermonsiz)')
source=source[:start]+body+source[end:]
result='// Generated by scripts/generate-native-mon.py; original policy and RNG order retained.\nexport function createNativeMonsterLifecycle(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n'
# Source MON has four visibility reads and four lvalue writes across hiding
# on level restore and monster flashing; the canonical pointer field stays raw.
visibility=subprocess.run([os.environ.get('NATIVE_NODE','node'),str(root/'scripts/native-mon-visibility.mjs')],input=result,text=True,capture_output=True,check=True)
result=visibility.stdout
print(visibility.stderr.strip())
# A second identical width conversion cannot change its already-normalized value.
compiled=subprocess.run([os.environ.get('NATIVE_NODE','node'),str(root/'scripts/native-idempotent-casts.mjs')],input=result,text=True,capture_output=True,check=True)
result=compiled.stdout
print(compiled.stderr.strip())
target=root/'js/nethack/native/monster-lifecycle.js'
if '--check' in sys.argv:
 assert target.read_text()==result
else:
 target.write_text(result)
