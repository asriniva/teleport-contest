"""Generate per-game lifecycle policies without the global C execution scope."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/mon.js').read_text()
names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
assert source.count("import {C} from '../c-runtime/context.js';")==1
source=source.replace("import {C} from '../c-runtime/context.js';",'')
source=re.sub(r'^export ','',source,flags=re.M)
source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
assert 'C.callLocal(' not in source
result='// Generated by scripts/generate-native-mon.py; original policy and RNG order retained.\nexport function createNativeMonsterLifecycle(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n'
(root/'js/nethack/native/monster-lifecycle.js').write_text(result)
