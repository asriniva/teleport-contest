"""Reproduce the per-game movement module from the reviewed policy source."""
from pathlib import Path
import re
root = Path(__file__).resolve().parent.parent
source = (root/'js/ported/monmove.js').read_text()
names = re.findall(r'^export (?:function|const) (\w+)', source, re.M)
source = source.replace("import {C} from '../c-runtime/context.js';", '')
source = re.sub(r'^export ', '', source, flags=re.M)
source = re.sub(r'C\.callLocal\((\w+), ', r'\1(', source)
# Track storage is an ordinary array; no byte addresses exist in native state.
source = source.replace('C.memset(mtmp.mtrack.address, 0, C.mtrackSize);', 'for (const point of mtmp.mtrack) { point.x = 0; point.y = 0; }')
source = source.replace('for (a = mdat.mattk[0]; a.address < mdat.mattk.address + C.NATTK * C.attackSize; a = C.attackNext(a)) {', 'for (let attackIndex = 0; attackIndex < C.NATTK; attackIndex++) {\n                a = mdat.mattk[attackIndex];')
source = source.replace('for (j = C.int(0); j < jcnt; mtrk = C.coordNext(mtrk), j++)\n                    if', 'for (j = C.int(0); j < jcnt; j++)\n                    if')
source = source.replace('nx == mtrk.x && ny == mtrk.y', 'nx == mtmp.mtrack[j].x && ny == mtmp.mtrack[j].y')
result = '// Generated by scripts/generate-native-monmove.py; policy order follows ported/monmove.js.\nexport function createNativeMonsterMovement(C) {\n' + source + '\nreturn Object.freeze({' + ','.join(names) + '});\n}\n'
(root/'js/nethack/native/monster-movement.js').write_text(result)
