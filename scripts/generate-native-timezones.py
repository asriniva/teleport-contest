#!/usr/bin/env python3
"""Generate immutable JS data from the explicitly pinned native macOS TZif tree.
TZDB data is public domain: https://data.iana.org/time-zones/tzdb/LICENSE.
No native code is generated or used by the production lookup service.
"""
import argparse, hashlib, json, pathlib, struct


def parse_tzif(data):
    def block(at, width):
        if data[at:at+4] != b'TZif':
            raise ValueError('bad TZif header')
        ut, std, leap, count, types, chars = struct.unpack_from('>6I', data, at+20)
        if not 1 <= types <= 256 or std not in (0, types) or ut not in (0, types):
            raise ValueError('invalid TZif counts')
        p = at+44
        transitions = list(struct.unpack_from('>'+str(count)+('q' if width == 8 else 'i'), data, p))
        p += count*width
        indexes = list(data[p:p+count]); p += count
        records = [struct.unpack_from('>iBB', data, p+6*i) for i in range(types)]; p += 6*types
        names = data[p:p+chars]; p += chars
        output = []
        for offset, daylight, name in records:
            end = names.find(b'\0', name)
            if end < 0 or daylight not in (0, 1):
                raise ValueError('invalid TZif type')
            output.append([offset, daylight, names[name:end].decode('ascii')])
        if any(index >= types for index in indexes) or any(a >= b for a,b in zip(transitions, transitions[1:])):
            raise ValueError('invalid TZif transitions')
        if leap:
            raise ValueError('leap-second TZif needs a separate timescale; not native POSIX tree')
        return [transitions, indexes, output], p+leap*(width+4)+std+ut
    parsed, end = block(0, 4)
    if data[4] in b'234':
        parsed, end = block(end, 8)
        footer = data[end:]
        if len(footer) < 2 or footer[:1] != b'\n' or footer[-1:] != b'\n':
            raise ValueError('invalid TZif footer')
        footer = footer[1:-1].decode('ascii')
    else:
        footer = ''
    if any(abs(t) > 2**53-1 for t in parsed[0]):
        raise ValueError('transition requires lossless BigInt encoding')
    return parsed+[footer]


def main():
    root = pathlib.Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--zoneinfo', type=pathlib.Path, default=pathlib.Path('/usr/share/zoneinfo'))
    parser.add_argument('--output', type=pathlib.Path, default=root/'js/platform/timezone/tzdb.js')
    parser.add_argument('--expect-version', default='2026c')
    args = parser.parse_args()
    version = (args.zoneinfo/'+VERSION').read_text().strip()
    if version != args.expect_version:
        raise SystemExit(f'Native TZDB changed: {version!r}, expected {args.expect_version!r}; review before regenerating')
    entries, ids, aliases, hashes = [], {}, {}, {}
    for file in sorted(args.zoneinfo.rglob('*')):
        if not file.is_file():
            continue
        data = file.read_bytes()
        if not data.startswith(b'TZif'):
            continue
        name = file.relative_to(args.zoneinfo).as_posix()
        hashes[name] = hashlib.sha256(data).hexdigest()
        parsed = parse_tzif(data)
        key = json.dumps(parsed, separators=(',', ':'))
        if key not in ids:
            ids[key] = len(entries); entries.append(parsed)
        aliases[name] = ids[key]
    metadata = dict(version=version, source='/usr/share/zoneinfo',
                    sourceVariant=(args.zoneinfo/'tzdata.zi').read_text().splitlines()[:3],
                    sourceSha256=hashlib.sha256((args.zoneinfo/'tzdata.zi').read_bytes()).hexdigest(),
                    license='Public domain IANA TZDB data; https://data.iana.org/time-zones/tzdb/LICENSE',
                    files=hashes)
    body = ('/* Generated by scripts/generate-native-timezones.py from pinned native macOS TZDB.\n'
            ' * IANA timezone data is public domain; source provenance and each input SHA256 below.\n'
            ' * Aliases deduplicate identical transition/type/footer data. No runtime host access. */\n')
    body += 'export const NATIVE_TIMEZONE_META='+json.dumps(metadata, separators=(',', ':'))+';\n'
    body += 'export const NATIVE_TIMEZONE_NAMES='+json.dumps(aliases, separators=(',', ':'))+';\n'
    body += 'export const NATIVE_TIMEZONE_ENTRIES='+json.dumps(entries, separators=(',', ':'))+';\n'
    args.output.write_text(body)
    print(f'Generated {len(aliases)} native TZif names / {len(entries)} unique entries, {len(body):,} bytes; TZDB {version}')


if __name__ == '__main__':
    main()
