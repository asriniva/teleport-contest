"""Bind original monster combat policy to its per-game native context."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/mhitm.js').read_text()
assert source.count("import { C } from '../c-runtime/context.js';")==1
names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
source=source.replace("import { C } from '../c-runtime/context.js';",'')
source=re.sub(r'^export ','',source,flags=re.M)
source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
assert 'C.callLocal(' not in source
(root/'js/nethack/native/mhitm.js').write_text('// Generated by scripts/generate-native-monster-combat.py; source policy and RNG order retained.\nexport function createNativeMonsterCombat(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n')
