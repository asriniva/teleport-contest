"""Bind unchanged glyph policy to per-game native state and direct local calls."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/glyphs.js').read_text()
context="import { C } from '../c-runtime/context.js';"
assert source.count(context)==1
names=[]
for line in source.splitlines():
 if line.startswith('export function '):names.append(re.match(r'export function (\w+)',line)[1])
 elif re.match(r'export (?:const|let|var) ',line):
  names.extend(re.findall(r'(?:export (?:const|let|var) |,\s*)(\w+)\s*=',line))
source=source.replace(context,'')
source=re.sub(r'^export ','',source,flags=re.M)
source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
assert 'C.callLocal(' not in source
(root/'js/nethack/native/glyphs.js').write_text('// Generated by scripts/generate-native-glyphs.py; original policy and mutation/RNG order retained.\nexport function createNativeGlyphs(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n')
