// Bind the complete attribute policy once per game; preserve local call order.
import fs from 'node:fs';
import {parse} from 'acorn';
let source=fs.readFileSync('js/ported/attrib.js','utf8');
const ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),names=[];
for(const n of ast.body)if(n.type==='ExportNamedDeclaration'){
 const d=n.declaration;if(d.id)names.push(d.id.name);else for(const row of d.declarations)names.push(row.id.name);
}
const context="import { C } from '../c-runtime/context.js';";
if(source.split(context).length!==2)throw Error('Changed attribute source import');
source=source.replace(context,'').replace(/^([ \t]*)export /gm,'$1').replace(/C\.callLocal\((\w+),\s*/g,'$1(').replace(/C\.callLocal\((\w+)\)/g,'$1()');
source=source.replace(/C\.u\.(abon|atemp|acurr)\.a\b/g,(_all,key)=>'C.'+({abon:'ABON',atemp:'ATEMP',acurr:'ABASE'})[key]);
if(source.includes('C.callLocal('))throw Error('Unreviewed local attribute call');
fs.writeFileSync('js/nethack/native/attrib.js','// Generated by scripts/generate-native-attrib.mjs; original policy and RNG order retained.\nexport function createNativeAttrib(C){\n'+source+'\nreturn {'+names.join(',')+'};\n}\n');
