import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createStandaloneEnvironment} from '../js/nethack/environment.js';
import {enableVision} from '../js/nethack/vision.js';
import {C,withCEnvironment} from '../js/c-runtime/context.js';
const layouts=JSON.parse(fs.readFileSync('js/wasm/tu-layouts.json'));
const env=createStandaloneEnvironment({initialBytes:1024,maximumBytes:128*1024*1024});
env.enableDecl(layouts.decl);
let calls=0;
env.register('deferred-visibility-probe',{});
env.deferFunctions('deferred-visibility-probe',{newsym(x,y){calls++;return x+y;}});
const {context}=enableVision(env,layouts);
assert.equal(env.services.newsym,undefined);
const first=context.newsym;
assert.equal(typeof first,'function','a first missing service lookup yields a deferred call');
const marker={foreignCaller:true};
withCEnvironment(marker,()=>{assert.equal(first(4,5),9);assert.equal(C,marker);});
assert.equal(calls,1);assert.equal(context.newsym(6,7),13);assert.equal(calls,2);
assert.equal(C,undefined);
const owner=context.nativeState,cell=context.levl[1][1];
const typ=env.ctypes.fieldAddress('struct rm',cell.address,'typ');
owner.enter();
cell.typ=layouts.vision.ROOM;
const epoch=owner.epoch;
assert.equal(env.memory.view.getInt8(typ),0);
context.viz_clear[0][0]=1;
assert.equal(context.viz_clear[0][0],1);
assert.equal(owner.epoch,epoch,'private workspace access retains native game fields');
assert.equal(env.memory.view.getInt8(typ),0,'private writes do not publish unrelated dirty map fields');
assert.ok(owner.dirty.size>0);
context.pointerBox(typ,{t:'i8'}).value=layouts.vision.DOOR;
assert.notEqual(owner.epoch,epoch,'an overlapping byte write invalidates native fields');
assert.equal(cell.typ,layouts.vision.DOOR);
owner.leave();assert.equal(owner.dirty.size,0);
console.log('PASS native visibility first/deferred service lookup, publication, repeated lookup and caller context restoration');
