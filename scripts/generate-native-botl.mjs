// Bind the complete status policy once per game; preserve local call order.
import fs from 'node:fs';
import {parse} from 'acorn';
let source=fs.readFileSync('js/ported/botl.js','utf8');
const ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),names=[];
for(const n of ast.body)if(n.type==='ExportNamedDeclaration'){
 const d=n.declaration;if(d.id)names.push(d.id.name);else for(const row of d.declarations)names.push(row.id.name);
}
const context="import {C} from '../c-runtime/context.js';";
if(source.split(context).length!==2)throw Error('Changed status source import');
source=source.replace(context,'').replace(/^([ \t]*)export /gm,'$1');
fs.writeFileSync('js/nethack/native/botl.js','// Generated by scripts/generate-native-botl.mjs; original policy and RNG order retained.\nexport function createNativeBotl(C){\n'+source+'\nreturn {'+names.join(',')+'};\n}\n');
