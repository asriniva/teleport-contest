"""Generate game-bound hero movement while retaining source policy/RNG order."""
from pathlib import Path
import re
import os
import sys
import subprocess
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/hack.js').read_text()
assert source.count("import { C } from '../c-runtime/context.js';")==1
names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
source=source.replace("import { C } from '../c-runtime/context.js';",'')
source=re.sub(r'^export ','',source,flags=re.M)
source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
assert 'C.callLocal(' not in source
# Native consumers replace the sole primitive-pointer grid write, travel scratch
# grids (which have no byte consumer), the optional prompt buffer and debug
# weight-table indexing. Source branch/RNG/mutation order remains unchanged.
old='((_hackTarget,_hackIndex)=>_hackTarget[_hackIndex] = C.uchar(C.int(C.int(_hackTarget[_hackIndex]) | C.int(C.IN_SIGHT))))(C.gv.viz_array[ry],rx)'
assert source.count(old)==1
source=source.replace(old,'C.writeVisibility(ry,rx,C.uchar(C.int(C.int(C.readVisibility(ry,rx)) | C.int(C.IN_SIGHT))))')
assert source.count('C.localArray("coordxy",[80, 21])')==1
assert source.count('C.localArray("coordxy",[2, 1680])')==2
source=source.replace('C.localArray("coordxy",[80, 21])','C.nativeTravelGrid(80,21)').replace('C.localArray("coordxy",[2, 1680])','C.nativeTravelGrid(2,1680)')
assert source.count('C.memset(( travel), 0, BigInt(2*80*21))')==1
source=source.replace('C.memset(( travel), 0, BigInt(2*80*21))','C.clearTravelGrid(travel)')
assert source.count('let qbuf = C.localArray("char",[128]);')==1
source=source.replace('let qbuf = C.localArray("char",[128]);','let qbuf = C.nativePromptBuffer(128);')
source=re.sub(r'C\.weightlist\[([^]\n]+)\]',r'C.weightAt(\1)',source)
assert source.count('lev[y].roomno')==3
source=source.replace('lev[y].roomno','C.advanceRecord(lev,y).roomno')
assert 'C.gv.viz_array' not in source and 'C.weightlist[' not in source
result=('// Generated by scripts/generate-native-hack.py; original policy and RNG order retained.\nexport function createNativeHeroMovement(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n')

compiled=subprocess.run([os.environ.get('NATIVE_NODE','node'),str(root/'scripts/native-scalar-casts.mjs'),'--measured-roots'],input=result,text=True,capture_output=True,check=True)
result=compiled.stdout
print(compiled.stderr.strip())
target=root/'js/nethack/native/hero-movement.js'
if '--check' in sys.argv:
 assert target.read_text()==result
else:
 target.write_text(result)
