"""Generate game-bound vision policies without changing their expressions."""
from pathlib import Path
import re
import sys
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/vision.js').read_text()
assert source.count("import {C} from '../c-runtime/context.js';")==1
names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
source=source.replace("import {C} from '../c-runtime/context.js';",'')
source=re.sub(r'^export ','',source,flags=re.M)
result='// Generated by scripts/generate-native-vision.py; original policy and call order retained.\nexport function createNativeVision(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n'
target=root/'js/nethack/native/vision.js'
if '--check' in sys.argv:
    assert target.read_text()==result,'Native vision generator drift'
else:
    target.write_text(result)
