// Compile fixed entry signatures from the original engine source. No eval or
// runtime code generation; the existing source/ABI metadata stays authoritative.
import fs from 'node:fs';import assert from 'node:assert/strict';import {parse} from 'acorn';
const ports=JSON.parse(fs.readFileSync('js/nethack/address-ports.json')).ports;
ports.cmd={schema:JSON.parse(fs.readFileSync('js/nethack/command-abi.json')).schema};
const factoryPorts=new Set(['mkobj','muse','pray','detect']),counts={};
let output='// Generated by scripts/generate-native-address-entries.mjs.\nexport function bindNativeAddressEntry(port,name,state,owner,services,legacy,cast){\n';
for(const [port,{schema}]of Object.entries(ports)){
 const source=fs.readFileSync('js/ported/'+port+'.js','utf8'),ast=parse(source,{ecmaVersion:'latest',sourceType:'module'});
 const definitions=ast.body.filter(n=>n.type==='ExportNamedDeclaration'&&n.declaration?.type==='FunctionDeclaration').map(n=>n.declaration);
 output+='if(port==='+JSON.stringify(port)+')switch(name){\n';let count=0,variadic=0;
 for(const fn of definitions){
  const name=fn.id.name;if(/StaticInitializers$/.test(name))continue;assert.ok(!['port','name','state','owner','services','legacy','cast','BigInt','undefined','arguments'].includes(name),'Native entry binding collision '+port+'.'+name);
  if(fn.params.some(p=>p.type!=='Identifier')||schema.functionTypes?.[name]?.includes('...')){variadic++;continue;}
  const args=fn.params.map((_,i)=>'p'+i),values=args.map((_,i)=>'v'+i),steps=[];
  for(const [i,p]of args.entries()){
   steps.push('let v'+i+'='+p+';if(v'+i+'&&v'+i+'.address!==undefined)v'+i+'=v'+i+'.address;');
   if(port==='cmd'||port==='sp_lev'){
    const t=schema.sourceParameters[name]?.[i]?.canonical;assert.equal(typeof t,'string',port+'.'+name+':'+i);
    if(port==='cmd'&&t.includes('*'))steps.push('if(typeof v'+i+"==='string')v"+i+'=services.literal(v'+i+');');
    steps.push('v'+i+'=state.context.'+(t==='long'?'i64':t==='unsigned long'?'u64':'ptr')+'(v'+i+');');
   }else if(port==='mkobj')steps.push('v'+i+'=cast('+JSON.stringify(name)+','+i+',v'+i+');');
  }
  // Source pointer values stay native on the internal edge. Foreign callers
  // keep the original bridge and its public result convention.
  const ret=schema.sourceReturns?.[name],pointerResult=(port==='cmd'||port==='sp_lev')&&ret?.includes('*');
  const result=pointerResult?"const value=state.namespace."+name+'('+values.join(',')+');return typeof value===\'string\'?services.literal(value):value?.address??value??0;':
   'return state.namespace.'+name+'('+values.join(',')+')'+(factoryPorts.has(port)||port==='cmd'||port==='sp_lev'?'':'??0')+';';
  output+='case '+JSON.stringify(name)+':return function '+name+'('+args.join(',')+'){if(state.ready&&owner.depth>0&&(!state.scope||state.scope.services===services)&&arguments.length==='+args.length+'){'+steps.join('')+result+'}return legacy(...arguments);};\n';count++;
 }
 output+='}\n';counts[port]={fixedEntries:count,variadicOrRest:variadic};
}
output+='}\n';parse(output,{ecmaVersion:'latest',sourceType:'module'});
const file='js/nethack/native/address-entries.js';if(process.argv.includes('--check'))assert.equal(fs.readFileSync(file,'utf8'),output);else fs.writeFileSync(file,output);
console.log(JSON.stringify(counts));
