// Bind original sound policy and lower local calls without changing RNG/order.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import {parse} from 'acorn';
const source=fs.readFileSync('js/ported/sounds.js','utf8'),ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),edits=[],names=[];
function visit(node){
 if(!node||typeof node!=='object')return;
 if(node.type==='CallExpression'&&node.callee.type==='MemberExpression'&&node.callee.object.name==='C'&&node.callee.property.name==='callLocal'){
  const [fn,...args]=node.arguments;assert.equal(fn.type,'Identifier');edits.push([node.start,args.length?args[0].start:node.end-1,fn.name+'(']);
 }
 for(const value of Object.values(node))if(Array.isArray(value))value.forEach(visit);else if(value&&typeof value==='object')visit(value);
}
for(const node of ast.body){
 if(node.type==='ImportDeclaration'){assert.equal(node.source.value,'../c-runtime/context.js');assert.equal(node.specifiers.length,1);assert.equal(node.specifiers[0].local.name,'C');edits.push([node.start,node.end,'']);}
 if(node.type==='ExportNamedDeclaration'){const d=node.declaration;assert.ok(d);edits.push([node.start,d.start,'']);if(d.id)names.push(d.id.name);else for(const row of d.declarations)names.push(row.id.name);}
 visit(node);
}
let body=source;for(const [start,end,text] of edits.sort((a,b)=>b[0]-a[0]))body=body.slice(0,start)+text+body.slice(end);
const result='// Generated by scripts/generate-native-sounds.mjs; source policy and RNG order retained.\nexport function createNativeSounds(C){\n'+body+'\nreturn {'+names.join(',')+'};\n}\n';parse(result,{ecmaVersion:'latest',sourceType:'module'});
const path='js/nethack/native/sounds.js';if(process.argv.includes('--check'))assert.equal(fs.readFileSync(path,'utf8'),result);else fs.writeFileSync(path,result);
