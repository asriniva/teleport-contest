// Bind the complete eating policy once per game; preserve local call order.
import fs from 'node:fs';
import {parse} from 'acorn';
let source=fs.readFileSync('js/ported/eat.js','utf8');
const ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),names=[];
for(const n of ast.body)if(n.type==='ExportNamedDeclaration'){
 const d=n.declaration;if(d.id)names.push(d.id.name);else for(const row of d.declarations)names.push(row.id.name);
}
const context="import {C} from '../c-runtime/context.js';";
if(source.split(context).length!==2)throw Error('Changed eating source import');
source=source.replace(context,'').replace(/^([ \t]*)export /gm,'$1').replace(/C\.callLocal\((\w+),\s*/g,'$1(').replace(/C\.callLocal\((\w+)\)/g,'$1()');
if(source.includes('C.callLocal('))throw Error('Unreviewed local eating call');
fs.writeFileSync('js/nethack/native/eat.js','// Generated by scripts/generate-native-eat.mjs; original policy and RNG order retained.\nexport function createNativeEat(C){\n'+source+'\nreturn {'+names.join(',')+'};\n}\n');
