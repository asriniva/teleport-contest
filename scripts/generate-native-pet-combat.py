"""Bind unchanged pet and monster-attack policies to per-game native contexts."""
from pathlib import Path
import re
root=Path(__file__).resolve().parent.parent
for name,factory in [('dogmove','createNativePetMovement'),('mhitu','createNativeMonsterAttack')]:
 source=(root/f'js/ported/{name}.js').read_text()
 assert source.count("import { C } from '../c-runtime/context.js';")==1
 names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
 source=source.replace("import { C } from '../c-runtime/context.js';",'')
 source=re.sub(r'^export ','',source,flags=re.M)
 source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
 source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
 assert 'C.callLocal(' not in source
 (root/f'js/nethack/native/{name}.js').write_text('// Generated by scripts/generate-native-pet-combat.py; source policy and RNG order retained.\nexport function '+factory+'(C) {\n'+source+'\nreturn Object.freeze({'+','.join(names)+'});\n}\n')
