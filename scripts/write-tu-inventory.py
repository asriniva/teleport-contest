#!/usr/bin/env python3
"""Inventory original C sources and migration gates without changing them."""

import collections
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / "nethack-c/upstream"


def main():
    sources = sorted(UPSTREAM.rglob("*.c"))
    by_stem = collections.defaultdict(list)
    for source in sources:
        by_stem[source.stem].append(source.relative_to(UPSTREAM).as_posix())

    # This file records HOBJ, not the entire link. Sysunix also links DATE_O
    # and TARGET_HACKLIB; the latter contains hacklib.o.
    objects = (ROOT / "js/wasm/link-objects.txt").read_text().splitlines()
    game_stems = {Path(obj).stem for obj in objects if obj.strip()}
    game_stems.update(("date", "hacklib"))
    ports = json.loads((ROOT / "nethack-c/wasm/tu-ports.json").read_text())
    game_stems.update(port["name"] for port in ports)
    game_paths = set()
    ambiguous = {}
    missing = []
    for stem in sorted(game_stems):
        matches = by_stem.get(stem, [])
        if len(matches) == 1:
            game_paths.add(matches[0])
        elif matches:
            ambiguous[stem] = matches
        else:
            missing.append(stem)

    # Registration marks build selection, never successful validation.
    states = {}
    for line in (ROOT / "PORTING_PROGRESS.md").read_text().splitlines():
        cells = [cell.strip() for cell in line.split("|")]
        if len(cells) >= 7 and cells[1].isdigit():
            source, state = cells[2].strip("`"), cells[4]
            if state not in ("Passed", "In progress", "Canonical restored"):
                raise ValueError(f"Unrecognized migration state: {state!r}")
            if not (UPSTREAM / source).is_file():
                raise ValueError(f"Missing ledger source: {source}")
            states[source] = state

    counts = collections.Counter(states.values())
    lines = [
        "# Original C source inventory",
        "",
        "Generated by `python3 -B scripts/write-tu-inventory.py` from the pristine",
        "upstream checkout, current game object list, port registry and migration ledger.",
        "",
        f"The checkout contains **{len(sources)} original `.c` files**, including",
        f"**{sum(source.parent == UPSTREAM / 'src' for source in sources)} directly under `src/`**.",
        "The requested 1,000 distinct original TUs cannot be supplied by this checkout.",
        "A C source file is an inventory item, not proof of a standalone compiled TU:",
        "some files belong to inactive platforms or utilities, or may be included by",
        "other source files. Headers, vendored libraries and new probes are not counted.",
        "",
        f"**{len(game_paths)} sources map uniquely to the current game build selection.**",
        "This selection combines the actual `HOBJ` entries in",
        "[link-objects.txt](js/wasm/link-objects.txt), `date.c`, `hacklib.c`, and registered",
        "JS replacements. The prepared `src/Makefile` links `DATE_O` and",
        "`TARGET_HACKLIB` separately from `HOBJ`. Selection can include a pending",
        "replacement and does not certify its gates have passed.",
        "",
        f"Migration ledger: **{counts['Passed']} Passed**, **{counts['Canonical restored']} Canonical restored**, **{counts['In progress']} In progress**,",
        f"**{len(sources) - len(states)} Not started** across all inventoried sources.",
        "`Passed` in [PORTING_PROGRESS.md](PORTING_PROGRESS.md) records validated translations;",
        "`Canonical restored` records reused frozen infrastructure separately.",
        "registry membership alone does not. Sources outside the selected game are",
        "labelled `Other target / utility`; their compilation and portability are unverified.",
        "",
    ]
    if ambiguous:
        lines += ["Ambiguous game object names (not assigned a source):", ""]
        lines += [f"- `{stem}`: {', '.join(f'`{p}`' for p in paths)}"
                  for stem, paths in ambiguous.items()]
        lines += [""]
    else:
        lines += ["No ambiguous game object names.", ""]
    if missing:
        lines += ["Unmatched game object names: " + ", ".join(f"`{s}`" for s in missing), ""]
    lines += ["| Original source | Lines | Scope | Migration status |",
              "|---|---:|---|---|"]
    for source in sources:
        path = source.relative_to(UPSTREAM).as_posix()
        line_count = len(source.read_bytes().splitlines())
        scope = "Current game" if path in game_paths else "Other target / utility"
        lines.append(f"| [{path}](nethack-c/upstream/{path}) | {line_count} | "
                     f"{scope} | {states.get(path, 'Not started')} |")
    (ROOT / "TU_INVENTORY.md").write_text("\n".join(lines) + "\n")
    print(f"{len(sources)} original C sources; {len(game_paths)} uniquely mapped game sources; "
          f"{counts['Passed']} passed; {counts['Canonical restored']} canonical restored; {counts['In progress']} in progress; "
          f"{len(ambiguous)} ambiguous; {len(missing)} unmatched")


if __name__ == "__main__":
    main()
