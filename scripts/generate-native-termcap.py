"""Bind complete terminal source policy per game; retain ordering and constants."""
from pathlib import Path
import re
import sys
root=Path(__file__).resolve().parent.parent
source=(root/'js/ported/termcap.js').read_text()
assert source.count("import { C } from '../c-runtime/context.js';")==1
names=re.findall(r'^export (?:function|const|let|var) (\w+)',source,re.M)
source=source.replace("import { C } from '../c-runtime/context.js';",'')
source=re.sub(r'^export ','',source,flags=re.M)
source=re.sub(r'C\.callLocal\((\w+),\s*',r'\1(',source)
source=re.sub(r'C\.callLocal\((\w+)\)',r'\1()',source)
assert 'C.callLocal(' not in source
# Keep the source serializer as the genuine byte-level fallback. Production
# marker capture uses the same cell state directly, without a C output buffer.
needle='function nomux_emit_marker(kind)\n{'
assert source.count(needle)==1
# The markers-enabled decision must precede the optimized capture branch.
start=source.index(needle)
at=source.index('    {\n',start)
source=source[:at]+'    if (C.captureNativeFrame) { C.captureNativeFrame(kind); return; }\n'+source[at:]
result='// Generated by scripts/generate-native-termcap.py; original terminal policy/order retained.\nexport function createNativeTermcap(C){\n'+source+'\nreturn {'+','.join(names)+'};\n}\n'
target=root/'js/nethack/native/termcap.js'
if '--check' in sys.argv:assert target.read_text()==result
else:target.write_text(result)
