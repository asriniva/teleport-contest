// Bind unchanged source policy to one native game context.
import fs from 'node:fs';
import {parse} from 'acorn';
const [name,factory]=process.argv.slice(2);
if(!/^[a-z_]+$/.test(name??'')||!/^createNative[A-Z]\w+$/.test(factory??''))throw Error('Expected module and native factory name');
const source=fs.readFileSync('js/ported/'+name+'.js','utf8'),ast=parse(source,{ecmaVersion:'latest',sourceType:'module'}),edits=[],names=[];
for(const node of ast.body){
 if(node.type==='ImportDeclaration'){
  if(node.source.value!=='../c-runtime/context.js'||node.specifiers.length!==1||node.specifiers[0].local.name!=='C')throw Error('Review native policy import '+name);
  edits.push([node.start,node.end,'']);
 }
 if(node.type==='ExportNamedDeclaration'){
  const d=node.declaration;if(!d)throw Error('Review native re-export '+name);
  edits.push([node.start,d.start,'']);if(d.id)names.push(d.id.name);else for(const row of d.declarations)names.push(row.id.name);
 }
}
if(names.includes(factory))throw Error('Native factory binding collision');
let body=source;for(const [start,end,value]of edits.sort((a,b)=>b[0]-a[0]))body=body.slice(0,start)+value+body.slice(end);
const output='// Generated by scripts/generate-native-bound.mjs; original policy and RNG order retained.\nexport function '+factory+'(C){\n'+body+'\nreturn {'+names.join(',')+'};\n}\n';
parse(output,{ecmaVersion:'latest',sourceType:'module'});fs.writeFileSync('js/nethack/native/'+name+'.js',output);
