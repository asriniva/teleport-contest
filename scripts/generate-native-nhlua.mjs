// Bind the entire NHLUA graph once per game; retain the shared source schema.
import fs from 'node:fs';import assert from 'node:assert/strict';import {parse} from 'acorn';
const source=fs.readFileSync('js/ported/nhlua.js','utf8'),ast=parse(source,{ecmaVersion:'latest',sourceType:'module',preserveParens:true}),edits=[],names=[];
const scalarTypes=new Set(['i8','u8','i16','u16','i32','u32','i64','u64','f32','f64']);
const fields=new Map(),reads=new Set(),writes=new Set();
function lower(node){
 if(!node||typeof node!=='object')return;
 if(Array.isArray(node)){node.forEach(lower);return;}
 if(node.type==='CallExpression'&&node.callee.object?.name==='C'){
  const operation=node.callee.property?.name;
  const [at,type,member]=node.arguments;
  if(operation==='field'&&type?.type==='Literal'&&member?.type==='Literal'){
   const key=JSON.stringify([type.value,member.value]);
   if(!fields.has(key))fields.set(key,{name:'fieldAt'+fields.size,record:type.value,field:member.value});
   edits.push([node.callee.start,node.callee.end,fields.get(key).name],[at.end,member.end,'']);
  }else if(['read','write'].includes(operation)&&type?.type==='Literal'&&scalarTypes.has(type.value)){
   (operation==='read'?reads:writes).add(type.value);
   edits.push([node.callee.start,node.callee.end,operation+'At_'+type.value],[at.end,type.end,'']);
  }
 }
 for(const value of Object.values(node))lower(value);
}
for(const node of ast.body){
 if(node.type==='ImportDeclaration'){assert.equal(node.source.value,'../c-runtime/context.js');assert.equal(node.specifiers.length,1);assert.equal(node.specifiers[0].local.name,'C');edits.push([node.start,node.end,'']);}
 if(node.type==='ExportNamedDeclaration'){
  const d=node.declaration;if(d.type==='VariableDeclaration'&&d.declarations[0].id.name==='nhluaSchema'){edits.push([node.start,node.end,'']);continue;}
  assert.equal(d.type,'FunctionDeclaration');names.push(d.id.name);edits.push([node.start,d.start,'']);lower(d.body);
 }
}
let body=source;for(const[a,b,value]of edits.sort((a,b)=>b[0]-a[0]))body=body.slice(0,a)+value+body.slice(b);
body=body.replace(/C\.callLocal\((\w+),\s*/g,'$1(').replace(/C\.callLocal\((\w+)\)/g,'$1()');assert.ok(!body.includes('C.callLocal('));
const declarations=[
 ...Array.from(fields.values(),({name,record,field})=>'const '+name+'=C.bindField('+JSON.stringify(record)+','+JSON.stringify(field)+');'),
 ...Array.from(reads,type=>'const readAt_'+type+'=C.scalarReads.'+type+';'),
 ...Array.from(writes,type=>'const writeAt_'+type+'=C.scalarWrites.'+type+';'),
];
const result='// Generated by scripts/generate-native-nhlua.mjs; source policy/RNG order retained.\nexport function createNativeNhlua(C){\n'+declarations.join('\n')+'\n'+body+'\nreturn {'+names.join(',')+'};\n}\n';parse(result,{ecmaVersion:'latest',sourceType:'module'});fs.writeFileSync('js/nethack/native/nhlua.js',result);
