// REPORT typed ABI imports only; report algorithms are in report.js.
addToLibrary({
  $teleportReportServices__deps: ['teleport_report_global', 'teleport_report_errno', 'teleport_report_environ', 'teleport_report_handler', 'teleport_report_open', 'teleport_report_execve', 'teleport_report_waitpid', 'teleport_report_signal', 'teleport_report_raw_print', 'teleport_report_pline', 'teleport_report_format', 'nhmd4_init', 'nhmd4_update', 'nhmd4_final', 'teleport_report_readlink', 'teleport_report_read', 'teleport_report_write', 'teleport_report_close', 'teleport_report_fork', 'teleport_report_exit', 'strcpy', 'strlen', 'strchr', 'memcpy', 'isalnum', 'version_string', 'getversionstring', 'strerror', 'NH_abort', '$stackAlloc', '$stringToUTF8OnStack'],
  $teleportReportServices: function() {
    var text = value => typeof value === 'string' ? BigInt(stringToUTF8OnStack(value)) : BigInt(value || 0);
    return {
      moduleKey: Module,
      heap: () => HEAPU8,
      signedHeap: () => HEAP8,
      stackAlloc: size => Number(stackAlloc(size)),
      text: value => Number(text(value)),
      global: (field) => Number(_teleport_report_global(field)),
      errnoPointer: () => Number(_teleport_report_errno()),
      environ: () => Number(_teleport_report_environ()),
      panictraceHandler: () => Number(_teleport_report_handler()),
      open: (path, flags, mode) => _teleport_report_open(text(path), flags, mode),
      execve: (file, argv, env) => _teleport_report_execve(text(file), BigInt(argv), BigInt(env)),
      waitpid: (pid, status, flags) => _teleport_report_waitpid(pid, BigInt(status), flags),
      signal: (sig, handler) => Number(_teleport_report_signal(sig, BigInt(handler))),
      raw_print: (value) => _teleport_report_raw_print(text(value)),
      pline: (format, value) => _teleport_report_pline(text(format), text(value)),
      format: (out, kind, number, a, b) => _teleport_report_format(BigInt(out), kind, number, BigInt(a), BigInt(b)),
      nhmd4_init: (ctx) => _nhmd4_init(BigInt(ctx)),
      nhmd4_update: (ctx, input, size) => _nhmd4_update(BigInt(ctx), BigInt(input), BigInt(size)),
      nhmd4_final: (ctx, out) => _nhmd4_final(BigInt(ctx), BigInt(out)),
      readlink: (path, out, size) => Number(_teleport_report_readlink(text(path), BigInt(out), BigInt(size))),
      read: (fd, out, size) => Number(_teleport_report_read(fd, BigInt(out), BigInt(size))),
      write: (fd, input, size) => Number(_teleport_report_write(fd, BigInt(input), BigInt(size))),
      close: (fd) => _teleport_report_close(fd),
      fork: () => _teleport_report_fork(),
      exit: (code) => _teleport_report_exit(code),
      Strcpy: (out, input) => Number(_strcpy(BigInt(out), text(input))),
      strlen: (input) => Number(_strlen(text(input))),
      strchr: (input, chr) => Number(_strchr(text(input), chr)),
      memcpy: (out, input, size) => Number(_memcpy(BigInt(out), text(input), BigInt(size))),
      isalnum: (chr) => _isalnum(chr),
      version_string: (out, size) => Number(_version_string(BigInt(out), BigInt(size))),
      getversionstring: (out, size) => Number(_getversionstring(BigInt(out), BigInt(size))),
      strerror: (error) => Number(_strerror(error)),
      NH_abort: (why) => _NH_abort(BigInt(why)),
    };
  },
  $teleportReportCall__deps: ['$teleportReportServices', '$stackSave', '$stackRestore'],
  $teleportReportCall: function(name, ...args) {
    var stack = stackSave();
    try { return Module['nethackPorted'].report(teleportReportServices(), name, ...args); }
    finally { stackRestore(stack); }
  },
  crashreport_init__deps: ['$teleportReportCall'], crashreport_init__sig: 'vip',
  crashreport_init: function(argc, argv) { return teleportReportCall('crashreport_init', argc, argv); },
  crashreport_bidshow__deps: ['$teleportReportCall'], crashreport_bidshow__sig: 'v',
  crashreport_bidshow: function() { return teleportReportCall('crashreport_bidshow'); },
  swr_add_uricoded__deps: ['$teleportReportCall'], swr_add_uricoded__sig: 'ipppp',
  swr_add_uricoded: function(input, out, remaining, markp) { return teleportReportCall('swr_add_uricoded', input, out, remaining, markp); },
  submit_web_report__deps: ['$teleportReportCall'], submit_web_report__sig: 'iipp',
  submit_web_report: function(cos, msg, why) { return teleportReportCall('submit_web_report', cos, msg, why); },
  dobugreport__deps: ['$teleportReportCall'], dobugreport__sig: 'i',
  dobugreport: function() { return teleportReportCall('dobugreport'); },
  NH_panictrace_libc__deps: ['$teleportReportCall'], NH_panictrace_libc__sig: 'i',
  NH_panictrace_libc: function() { return teleportReportCall('NH_panictrace_libc'); },
  NH_panictrace_gdb__deps: ['$teleportReportCall'], NH_panictrace_gdb__sig: 'i',
  NH_panictrace_gdb: function() { return teleportReportCall('NH_panictrace_gdb'); },
  get_saved_pline__deps: ['$teleportReportCall'], get_saved_pline__sig: 'pi',
  get_saved_pline: function(lineno) { return teleportReportCall('get_saved_pline', lineno); },
  panictrace_handler__deps: ['$teleportReportCall'], panictrace_handler__sig: 'vi',
  panictrace_handler: function(sig_unused) { return teleportReportCall('panictrace_handler', sig_unused); },
  panictrace_setsignals__deps: ['$teleportReportCall'], panictrace_setsignals__sig: 'vi',
  panictrace_setsignals: function(set) { return teleportReportCall('panictrace_setsignals', set); },
});
